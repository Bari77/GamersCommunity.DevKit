/**
 * Regenerates `src/link-networks.ts` from simple-icons (CC0-1.0).
 * Run with `node scripts/gen-link-networks.mjs` after adding a network below.
 */
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

/** `icon` is the simple-icons slug; `color` is picked to stay legible on a dark surface. */
const NETWORKS = [
    { key: 'youtube', label: 'YouTube', icon: 'youtube', color: '#FF0000' },
    { key: 'twitch', label: 'Twitch', icon: 'twitch', color: '#A970FF' },
    { key: 'twitter', label: 'X', icon: 'x', color: '#E7E9EA' },
    { key: 'instagram', label: 'Instagram', icon: 'instagram', color: '#E4405F' },
    { key: 'tiktok', label: 'TikTok', icon: 'tiktok', color: '#EE1D52' },
    { key: 'discord', label: 'Discord', icon: 'discord', color: '#5865F2' },
    { key: 'bluesky', label: 'Bluesky', icon: 'bluesky', color: '#0285FF' },
    { key: 'github', label: 'GitHub', icon: 'github', color: '#E6EDF3' },
    { key: 'reddit', label: 'Reddit', icon: 'reddit', color: '#FF4500' },
    { key: 'steam', label: 'Steam', icon: 'steam', color: '#C7D5E0' },
    { key: 'facebook', label: 'Facebook', icon: 'facebook', color: '#0866FF' },
    { key: 'patreon', label: 'Patreon', icon: 'patreon', color: '#F96854' },
];

const entries = [];
for (const network of NETWORKS) {
    const response = await fetch(`https://cdn.jsdelivr.net/npm/simple-icons@latest/icons/${network.icon}.svg`);
    if (!response.ok) {
        throw new Error(`${network.icon}: HTTP ${response.status}`);
    }

    const path = /<path d="([^"]+)"/.exec(await response.text())?.[1];
    if (!path) {
        throw new Error(`${network.icon}: no path found`);
    }

    entries.push({ ...network, path });
}

const body = entries
    .map(
        (entry) => `    {
        key: '${entry.key}',
        label: '${entry.label}',
        color: '${entry.color}',
        path: '${entry.path}',
    },`,
    )
    .join('\n');

const file = `/**
 * Brand glyphs for link cards, generated by \`scripts/gen-link-networks.mjs\`.
 * Paths come from simple-icons (CC0-1.0); colours are tuned for a dark surface.
 * Do not edit by hand.
 */

export interface GcLinkNetwork {
    key: string;
    label: string;
    color: string;
    /** 24x24 fill path. */
    path: string;
}

export const GC_LINK_NETWORKS: readonly GcLinkNetwork[] = [
${body}
];

const BY_KEY = new Map(GC_LINK_NETWORKS.map((network) => [network.key, network]));

/** Undefined for keys with no glyph, which the card renders as a generic link. */
export function gcLinkNetwork(key: string | null | undefined): GcLinkNetwork | undefined {
    return key ? BY_KEY.get(key.trim().toLowerCase()) : undefined;
}
`;

const target = join(dirname(fileURLToPath(import.meta.url)), '..', 'src', 'link-networks.ts');
writeFileSync(target, file, 'utf8');
console.log(`Wrote ${entries.length} networks to ${target}`);
